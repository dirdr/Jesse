"""Boundaries owned by the experiment use case."""
from typing import Any, Protocol

from jesse.recording.domain import Observation

class ExperimentRecords(Protocol):
    def session_started(self, session: dict[str, Any]) -> None: ...
    def event_received(self, event: dict[str, Any]) -> None: ...
    def record_observation(self, observation: Observation) -> dict[str, Any]: ...
    def analyze_measurements(self) -> dict[str, Any]: ...
    def save(self, session: dict, report: str) -> None: ...
    def finish(self, outcome: str, reason: str) -> None: ...


class DesktopAgent(Protocol):
    def run(self, instructions: str, records: ExperimentRecords) -> tuple[dict[str, Any], str]: ...
